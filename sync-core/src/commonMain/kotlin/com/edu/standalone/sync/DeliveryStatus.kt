package com.edu.standalone.sync

/** Состояние доставки операции удалённой стороне. */
enum class DeliveryStatus {
    /** Операция ожидает отправки или подтверждения, в том числе после временной ошибки. */
    PENDING,
    /** Удалённая сторона подтвердила успешное применение операции. */
    ACKNOWLEDGED,
    /** Удалённая сторона окончательно отклонила операцию; автоматический повтор не требуется. */
    REJECTED
}
